import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const root=process.argv[2]||'_site/pwa-local';
const read=f=>fs.readFileSync(root+'/'+f,'utf8');
const html=read('index.html');
const js=read('budget-app.js');
const css=read('budget.css');
const sw=read('sw.js');
const panel=read('local-controls.js');
const m=JSON.parse(read('manifest.webmanifest'));
assert.equal(m.id,'/pwa-local/');
assert.equal(m.start_url,'/pwa-local/');
assert.equal(m.scope,'/pwa-local/');
assert.equal(m.display,'standalone');
assert.ok(m.icons.some(x=>x.sizes==='192x192'));
assert.ok(m.icons.some(x=>x.sizes==='512x512'));
assert.ok(m.icons.some(x=>x.purpose==='maskable'));
for(const [name,x] of [['app',js],['SW',sw],['local controls',panel]])new vm.Script(x,{filename:name+'.js'});
assert.match(html,/v9\.68 · локально/);
assert.match(html,/href="\.\/manifest\.webmanifest\?v=968"/);
assert.match(html,/src="\.\/budget-app\.js\?v=968"/);
assert.match(html,/src="\.\/local-controls\.js\?v=968"/);
assert.doesNotMatch(html,/accounts\.google\.com|gsi\/client|lfp-login|oauth|pwa-bridge\.js|session-bridge\.js|script\.googleapis\.com/i);
assert.match(js,/async function boot\(\)\{\s*\/\/ В этой отдельной версии бюджет хранится только на устройстве/);
assert.match(js,/useLocal\(\);\s*\}/);
assert.match(js,/localStorage\.getItem\('lfp-device-local-v968-data'\)/);
assert.match(js,/localStorage\.setItem\('lfp-device-local-v968-data'/);
assert.doesNotMatch(js,/await window\.LFP_PWA\.ensureAuth\(\)/);
assert.doesNotMatch(js,/localStorage\.(getItem|setItem)\('bdds-data'/);
assert.match(js,/function compute\(/);
assert.match(js,/function computeBdr\(/);
assert.match(js,/function renderGoals\(/);
assert.ok(js.length>245000,'latest v9.68 finance logic must be present');
assert.ok(css.length>70000);
assert.match(panel,/const KEY='lfp-device-local-v968-data'/);
assert.match(panel,/input id="lfp-local-file"/);
assert.match(panel,/lfp-local-export/);
assert.match(panel,/beforeinstallprompt/);
assert.doesNotMatch(panel,/\bfetch\(|XMLHttpRequest|google\.accounts|scripts:run/);
assert.match(sw,/lfp-local-shell-v968-1/);
assert.match(sw,/url\.pathname\.startsWith\(BASE\.pathname\)/);
assert.doesNotMatch(sw,/oauth|auth-session|script\.googleapis\.com/i);
assert.doesNotMatch(sw,/\b(?:localStorage\.|indexedDB\.|finance_rpc|access_token|refresh_token)/i);
for(const file of ['icon-192.png','icon-512.png','icon-maskable-512.png','apple-touch-icon-180.png']){
  assert.ok(fs.statSync(root+'/'+file).size>200,'image is missing: '+file);
}
console.log('PASS: installable isolated /pwa-local/ v9.68 has zero Google sign-in, local storage, import/export, original finance formulas and only static SW caching');
