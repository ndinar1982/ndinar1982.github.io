import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const dir=path.dirname(fileURLToPath(import.meta.url));
const get=f=>fs.readFileSync(path.join(dir,f),'utf8');
const m=JSON.parse(get('manifest.webmanifest'));
assert.equal(m.name,'ЛФП — Семейный бюджет (тест PWA)');
assert.equal(m.id,'/pwa-preview/');
assert.equal(m.start_url,'/pwa-preview/');
assert.equal(m.scope,'/pwa-preview/');
assert.equal(m.display,'standalone');
assert.equal(m.prefer_related_applications,false);
assert.ok(m.icons.some(x=>x.sizes==='192x192'));
assert.ok(m.icons.some(x=>x.sizes==='512x512'));
assert.ok(m.icons.some(x=>x.purpose==='maskable'));
for(const u of [m.id,m.start_url,m.scope]){
  assert.ok(new URL(u,'https://ndinar1982.github.io').pathname.startsWith('/pwa-preview/'));
}
const worker=get('sw.js'),install=get('install-ui.js'),help=get('install-help.html');
new vm.Script(worker);new vm.Script(install);
assert.match(worker,/lfp-pwa-install-test-v968-1/);
assert.match(worker,/self\.registration\.scope/);
assert.match(worker,/if\(url\.origin!==BASE\.origin \|\| !url\.pathname\.startsWith\(BASE\.pathname\)\)return;/);
assert.doesNotMatch(worker,/cache\.put\(.*(?:rpc|scripts\/|Google|Token)/i);
assert.doesNotMatch(worker,/sessionStorage|localStorage|indexedDB|bearer/i);
assert.match(install,/beforeinstallprompt/);
assert.match(install,/\.prompt\(\)/);
assert.match(help,/<link rel="manifest" href="\.\/manifest\.webmanifest\?v=968">/);
assert.match(help,/navigator\.serviceWorker\.register\('\.\/sw\.js',\{scope:'\.\/'\}\)/);
const embedded=[...help.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
assert.equal(embedded.length,1);
new vm.Script(embedded[0]);
const workflow=fs.readFileSync(path.resolve(dir,'../.github/workflows/publish-lfp.yml'),'utf8');
assert.match(workflow,/cp "_site\/\$file" "_site\/pwa-preview\/\$file"/);
assert.match(workflow,/cmp _site\/budget-app\.js _site\/pwa-preview\/budget-app\.js/);
assert.match(workflow,/cmp _site\/pwa-bridge\.js _site\/pwa-preview\/pwa-bridge\.js/);
assert.match(workflow,/s=s\.replace\('v9\.68 Firebase','v9\.68 · PWA тест',1\)/);
console.log('PASS: PWA preview is standalone, isolated to /pwa-preview/, keeps v9.68 finance/auth immutable and caches no sensitive data');
